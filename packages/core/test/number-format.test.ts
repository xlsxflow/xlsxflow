describe('formatValue', () => {
  for (const [group, list] of Object.entries(cases)) {
    describe(group, () => {
      it.each(list)('%j with %s', (value, code, expected) => {
        expect(formatValue(value, code)).toBe(expected);
      });
    });
  }

  it('uses the 1904 date system', () => {
    expect(formatValue(0, 'yyyy-mm-dd', true)).toBe('1904-01-01');
    expect(formatValue(43538, 'yyyy-mm-dd dddd', true)).toBe('2023-03-15 Wednesday');
    expect(formatValue(new Date(Date.UTC(2023, 2, 15, 6)), 'yyyy-mm-dd h:mm', true)).toBe('2023-03-15 6:00');
    expect(formatValue(new Date(Date.UTC(2023, 2, 15)), 'General', true)).toBe('43538');
  });
});
